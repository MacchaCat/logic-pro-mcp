#!/bin/sh
# Builds what claude-plugin/ ships besides its hand-written files:
#   claude-plugin/server/logic-mcp          the server, Apple silicon, size-optimised
#   claude-plugin/THIRD_PARTY_LICENSES.md   licenses of everything linked into it
#   claude-plugin/LICENSE                   a copy of the repository's LICENSE
#
# Every file in a Claude plugin folder must stay under 5 MiB, so the binary is arm64 only,
# built with -Osize, stripped and ad-hoc signed again (strip invalidates the signature).
# It uses its own build directory (.build/plugin by default), so a server running from
# .build/release is left alone.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
plugin="$root/claude-plugin"
scratch="${LOGIC_MCP_PLUGIN_BUILD:-$root/.build/plugin}"
limit=5242880

swift build --package-path "$root" --scratch-path "$scratch" \
    -c release --product logic-mcp --arch arm64 -Xswiftc -Osize
bin=$(swift build --package-path "$root" --scratch-path "$scratch" \
    -c release --product logic-mcp --arch arm64 -Xswiftc -Osize --show-bin-path)

mkdir -p "$plugin/server"
out="$plugin/server/logic-mcp"
cp "$bin/logic-mcp" "$out.tmp"
strip -S -x "$out.tmp"
codesign --force --sign - "$out.tmp"
mv "$out.tmp" "$out"
chmod 755 "$out"

size=$(stat -f %z "$out")
lipo -info "$out"
"$out" version
echo "$out: $size bytes (limit $limit)"
if [ "$size" -ge "$limit" ]; then
    echo "error: the binary is too big for a plugin folder (each file must be under 5 MiB)" >&2
    exit 1
fi

cp "$root/LICENSE" "$plugin/LICENSE"

# Licenses: this repository's own notices, then every resolved package, verbatim.
licenses="$plugin/THIRD_PARTY_LICENSES.md"
{
    echo "# Third-party licenses"
    echo
    echo "\`server/logic-mcp\` is built from https://github.com/MacchaCat/logic-pro-mcp (MIT, see"
    echo "\`LICENSE\`). It contains the material below. This file is generated by"
    echo "\`scripts/build-plugin.sh\`."
    echo
    echo "## Material included in the source"
    echo
    sed '1,/^## /{/^## /!d;}' "$root/THIRD_PARTY_NOTICES.md" | sed 's/^## /### /'
    echo
    echo "## Swift packages linked into the server"
    for dir in "$scratch"/checkouts/*; do
        [ -d "$dir" ] || continue
        name=$(basename "$dir")
        version=$(sed -n "/\"identity\" : \"$name\"/,/\"version\"/s/.*\"version\" : \"\(.*\)\".*/\1/p" "$root/Package.resolved")
        echo
        echo "### $name ${version:-}"
        for file in "$dir"/LICENSE* "$dir"/NOTICE*; do
            [ -f "$file" ] || continue
            echo
            echo "\`$(basename "$file")\`:"
            echo
            echo '```'
            cat "$file"
            echo '```'
        done
    done
} > "$licenses"
echo "$licenses: $(stat -f %z "$licenses") bytes"
